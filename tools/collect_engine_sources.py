"""Inventory actual linked Go modules and collect hash-checked source archives.

Only `go version` and `go mod download` run. No dependency code, builds or tunnel
processes execute. Network downloads use the public Go proxy/checksum service.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[1]


def sha(path):
    with path.open('rb') as stream: return hashlib.file_digest(stream, 'sha256').hexdigest()


def main(go, output):
    output = output.resolve()
    if output.exists(): raise RuntimeError('Choose a fresh source inventory directory')
    lock = json.loads((ROOT/'third_party/sources/sing-box-lock.json').read_text('utf-8'))
    dep = ROOT/'work/dependencies'/('sing-box-'+lock['version'])
    engine = dep/'extracted'/('sing-box-'+lock['version']+'-windows-amd64')/'sing-box.exe'
    if sha(engine) != lock['executable_sha256']: raise RuntimeError('Engine hash differs')
    # No ambient private proxies, private module exceptions or workspace scripts.
    env = dict(os.environ)
    env.update(GOTOOLCHAIN='local', GOENV='off', GOWORK='off', GOPRIVATE='',
        GONOPROXY='', GONOSUMDB='', GOPROXY='https://proxy.golang.org',
        GOSUMDB='sum.golang.org', GOFLAGS='',
        GOMODCACHE=str(ROOT/'work/dependencies/go-module-cache'),
        GOPATH=str(ROOT/'work/dependencies/go-workspace'))
    build = json.loads(subprocess.check_output([str(go), 'version', '-m', '-json', str(engine)], env=env))
    settings = {r['Key']: r['Value'] for r in build['Settings']}
    if (build['Main'].get('Path') != 'github.com/sagernet/sing-box'
            or build['Main'].get('Version') != 'v'+lock['version']
            or settings.get('vcs.revision') != lock['source_commit']
            or settings.get('vcs.modified') != 'false'):
        raise RuntimeError('Embedded engine source identity differs')
    modules = build['Deps']
    if not modules or len(modules) > 1024: raise RuntimeError('Invalid module inventory')
    seen = set()
    for module in modules:
        if (set(module) != {'Path', 'Version', 'Sum'}
                or not re.fullmatch(r'[A-Za-z0-9._~+/-]{1,240}', module['Path'])
                or not re.fullmatch(r'v[0-9][A-Za-z0-9.+-]{0,160}', module['Version'])
                or not re.fullmatch(r'h1:[A-Za-z0-9+/]{43}=', module['Sum'])
                or module['Path'] in seen):
            raise RuntimeError('Unsupported or ambiguous linked module')
        seen.add(module['Path'])
    output.mkdir(parents=True)
    (output/'archives').mkdir()
    (output/'engine-buildinfo.json').write_text(json.dumps(build, indent=2), encoding='utf-8')

    def collect(module):
        identity = module['Path']+'@'+module['Version']
        result = {'module':module, 'verified':False}
        try:
            run = subprocess.run([str(go), 'mod', 'download', '-json', identity],
                cwd=output, env=env, capture_output=True, timeout=240)
            info = json.loads(run.stdout)
            if (run.returncode != 0 or info.get('Sum') != module['Sum']
                    or info.get('Path') != module['Path'] or info.get('Version') != module['Version']):
                raise RuntimeError('Download or embedded checksum verification failed: '+str(info.get('Error', 'identity mismatch')))
            source = Path(info['Zip'])
            # Cache paths are generated by Go, still constrain them before copy.
            source.resolve().relative_to(Path(env['GOMODCACHE']).resolve())
            name = hashlib.sha256(identity.encode()).hexdigest()+'.zip'
            target = output/'archives'/name
            shutil.copyfile(source, target)
            if sha(target) != sha(source): raise RuntimeError('Source archive copy differs')
            with zipfile.ZipFile(target) as archive:
                if archive.testzip() is not None: raise RuntimeError('Corrupt module source archive')
                license_names = [n for n in archive.namelist()
                    if re.match(r'(?i)^(license|copying|copyright|notice)(?:[._-].*)?$', Path(n).name)]
            result.update(verified=True, archive='archives/'+name, sha256=sha(target),
                bytes=target.stat().st_size, license_entries=license_names,
                license_review_complete=False)
        except Exception as error:
            result['error'] = str(error)[:1000]
        return result

    results = []
    with ThreadPoolExecutor(max_workers=4) as workers:
        pending = [workers.submit(collect, module) for module in modules]
        for future in as_completed(pending):
            results.append(future.result())
            if len(results)%20 == 0: print(json.dumps({'processed':len(results),'total':len(modules)}), flush=True)
    results.sort(key=lambda row:row['module']['Path'])
    receipt = {'schema':1, 'engine_sha256':lock['executable_sha256'],
        'source_commit':lock['source_commit'], 'go_toolchain':build['GoVersion'],
        'modules':results, 'all_module_sources_verified':all(row['verified'] for row in results),
        'license_review_complete':False, 'dependency_code_executed':False,
        'limits':['Linked Go modules only; Go standard library/toolchain source is separate.',
                  'Archive license-file inventory does not establish complete license compliance.',
                  'Original engine build reproducibility remains unverified.']}
    (output/'source-inventory.json').write_text(json.dumps(receipt, indent=2), encoding='utf-8')
    print(json.dumps({'modules':len(results),'verified':sum(r['verified'] for r in results),
                      'license_review_complete':False}), flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--go', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args(); main(args.go, args.output)
